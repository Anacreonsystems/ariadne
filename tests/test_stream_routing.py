def test_group_count_requires_an_exact_positive_integer(count: object):
    with pytest.raises(ValueError, match="exact positive integer"):
        tagged_key_v1_group(None, cast(int, count))


_CHILD_SCRIPT = r"""
import hashlib
import importlib.util
import json
import os
import sys
from pathlib import Path

path = Path(sys.argv[1])
spec = importlib.util.spec_from_file_location("routing_under_test", path)
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
values = [None, False, True, 0, -1, 1, "text", "é", "e\u0301", b"\xff\x00"]
rows = [
    [module.encode_tagged_key_v1(value).hex(),
     module.tagged_key_v1_group(value, 17),
     module.tagged_key_v1_group(value, 65537),
     module.tagged_key_v1_group(value, 1 << 300)]
    for value in values
]
print(json.dumps({"version": list(sys.version_info[:2]),
                  "seed": os.environ["PYTHONHASHSEED"],
                  "hash_probe": hash("café"),
                  "source_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                  "rows": rows}))
"""


@pytest.mark.parametrize("python_version", [(3, 11), (3, 12), (3, 13), (3, 14)])
def test_mapping_across_real_python_processes_and_hash_seeds(
    python_version: tuple[int, int], tmp_path: Path
):
    executable = (
        sys.executable
        if sys.version_info[:2] == python_version
        else shutil.which(f"python{python_version[0]}.{python_version[1]}")
    )
    if executable is None:
        pytest.skip(f"Python {python_version[0]}.{python_version[1]} is not installed")
    source = Path(stream_routing.__file__).resolve()
    expected = [
        [encoded_hex, group17, group65537, int(digest_hex, 16)]
        for _, encoded_hex, digest_hex, group17, group65537 in _ROUTING_GOLDENS
    ]
    salted_hashes: set[int] = set()
    for seed in ["0", "1", "42", "4294967295"]:
        completed = subprocess.run(
            [executable, "-S", "-c", _CHILD_SCRIPT, str(source)],
            env={**os.environ, "PYTHONHASHSEED": seed, "PYTHONDONTWRITEBYTECODE": "1"},
            cwd=tmp_path,
            capture_output=True,
            text=True,
            check=True,
            timeout=20,
        )
        result = json.loads(completed.stdout)
        assert result["version"] == list(python_version)
        assert result["seed"] == seed
        assert (
            result["source_sha256"] == hashlib.sha256(source.read_bytes()).hexdigest()
        )
        assert result["rows"] == expected
        salted_hashes.add(result["hash_probe"])
    # The negative control proves the requested hash seeds actually changed
    # Python's salted hash while the portable routing result stayed identical.
    assert len(salted_hashes) > 1
